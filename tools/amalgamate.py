#!/usr/bin/env python3
"""tools/amalgamate.py — generate the amalgamated distribution under dist/.

Outputs:
  dist/cpptoml.hpp                          public API + lib/detail inline
  dist/cpptoml.cpp                          all library TUs in one file
  dist/cpptoml/{value,parse,format}.hpp     shims for <cpptoml/...> includes

Splicing rules:
  * #pragma once inside spliced files is removed.
  * System/standard includes are hoisted to one sorted block per output file.
  * <cpptoml/...> includes are dropped: their content is inlined here.
  * Quoted includes resolve relative to the including file's directory and
    headers are emitted at first need (depth-first), never twice.

Deterministic: no timestamps, fixed iteration order — identical inputs give
byte-identical outputs. Regenerate with:  python tools/amalgamate.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "dist"

PUBLIC = [
    "include/cpptoml/value.hpp",
    "include/cpptoml/parse.hpp",
    "include/cpptoml/format.hpp",
]
LIB_CPPS = ["lib/parser.cpp", "lib/format.cpp", "lib/value.cpp"]

STD_RE = re.compile(r"^\s*#\s*include\s*<([^>]+)>\s*$")
CPPTOML_RE = re.compile(r"^\s*#\s*include\s*<cpptoml/([a-z]+\.hpp)>\s*$")
QUOTED_RE = re.compile(r"^\s*#\s*include\s*\"([^\"]+)\"\s*$")
ONCE_RE = re.compile(r"^\s*#\s*pragma\s+once\s*$")
VERSION_RE = re.compile(r'^\s*version\s*=\s*"([^"]+)"', re.MULTILINE)


def read(rel: str) -> list[str]:
    return (ROOT / rel).read_text(encoding="utf-8").splitlines()


def project_version() -> str:
    try:
        match = VERSION_RE.search((ROOT / "cizon.toml").read_text(encoding="utf-8"))
    except OSError:
        return ""
    return match.group(1) if match else ""


def splice(
    rel: str,
    chunks: list[tuple[str, list[str]]] | None,
    std: set[str],
    emitted: set[str],
    inline_quoted: bool,
) -> None:
    """Append the content of `rel` (minus includes/pragma once) to `chunks`.

    std includes land in `std`; `<cpptoml/...>` matches are drops (their
    content is amalgamated here). With `inline_quoted` set (header side),
    quoted includes are spliced recursively at first need; otherwise (source
    side) they are dropped, because their content already lives in
    cpptoml.hpp.
    """
    if rel in emitted:
        return
    emitted.add(rel)
    body: list[str] = []
    skip_blank = False  # collapse the blank left behind by a dropped include
    directory = (ROOT / rel).parent
    for line in read(rel):
        if skip_blank and line.strip() == "":
            skip_blank = False  # one follow-up blank is dropped with the include
            continue
        skip_blank = False
        if ONCE_RE.match(line):
            skip_blank = True
            continue
        m = STD_RE.match(line)
        if m:
            std.add(m.group(1))
            skip_blank = True
            continue
        m = CPPTOML_RE.match(line)
        if m:
            if m.group(1) not in {"value.hpp", "parse.hpp", "format.hpp"}:
                raise SystemExit(f"{rel}: unexpected internal include {m.group(1)}")
            skip_blank = True
            continue
        m = QUOTED_RE.match(line)
        if m:
            if not inline_quoted:
                skip_blank = True
                continue
            target = (directory / m.group(1)).resolve().relative_to(ROOT)
            splice(target.as_posix(), chunks, std, emitted, True)
            skip_blank = True
            continue
        body.append(line)
    if chunks is not None:
        chunks.append((rel, body))


def std_block(std: set[str]) -> list[str]:
    return [f"#include <{name}>" for name in sorted(std)]


def section(title: str) -> str:
    return f"// ===== {title} ====="


def banner(name: str, version: str) -> list[str]:
    lines = [
        f"// {name} — amalgamated distribution of cpptoml (version {version}).",
        "// GENERATED by tools/amalgamate.py; do not edit by hand.",
        "// Regenerate:  python tools/amalgamate.py",
    ]
    return lines


def make_header(version: str) -> str:
    std: set[str] = set()
    emitted: set[str] = set()
    public_chunks: list[tuple[str, list[str]]] = []
    for rel in PUBLIC:
        splice(rel, public_chunks, std, emitted, True)

    detail_chunks: list[tuple[str, list[str]]] = []
    for rel in LIB_CPPS:
        body = read(rel)
        directory = (ROOT / rel).parent
        for line in body:
            m = QUOTED_RE.match(line)
            if m:
                target = (directory / m.group(1)).resolve().relative_to(ROOT)
                splice(target.as_posix(), detail_chunks, std, emitted, True)

    out: list[str] = []
    out += banner("cpptoml.hpp", version)
    out.append("#pragma once")
    out.append("")
    out.append("// Standard headers used across the amalgamated library.")
    out += std_block(std)
    for rel, body in public_chunks:
        out += ["", section(rel)] + body
    for rel, body in detail_chunks:
        out += ["", section(rel)] + body
    out.append("")
    return "\n".join(out)


def make_source(version: str) -> str:
    std: set[str] = set()
    emitted: set[str] = set()
    chunks: list[tuple[str, list[str]]] = []
    for rel in LIB_CPPS:
        splice(rel, chunks, std, emitted, False)

    out: list[str] = []
    out += banner("cpptoml.cpp", version)
    out.append("")
    out.append('#include "cpptoml.hpp"')
    out.append("")
    out += std_block(std)
    for rel, body in chunks:
        out += ["", section(rel)] + body
    out.append("")
    return "\n".join(out)


def make_shim(name: str, version: str) -> str:
    lines = banner(f"cpptoml/{name}", version)
    lines += [
        "// Shim for <cpptoml/%s> consumers of the amalgamated distribution." % name,
        "#pragma once",
        "",
        '#include "../cpptoml.hpp"',
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    version = project_version()
    OUT.mkdir(exist_ok=True)
    (OUT / "cpptoml.hpp").write_text(make_header(version), encoding="utf-8", newline="\n")
    (OUT / "cpptoml.cpp").write_text(make_source(version), encoding="utf-8", newline="\n")
    shim_dir = OUT / "cpptoml"
    shim_dir.mkdir(exist_ok=True)
    for name in ("value.hpp", "parse.hpp", "format.hpp"):
        (shim_dir / name).write_text(make_shim(name, version), encoding="utf-8", newline="\n")
    print(f"dist refreshed (cpptoml {version or 'version unknown'}): "
          "cpptoml.hpp, cpptoml.cpp, cpptoml/*.hpp shims")


if __name__ == "__main__":
    main()
